def test_settings_read_by_two_ranges(server, monkeypatch):
    monkeypatch.setattr(kp, "TAIL_BYTES", 2048)
    big = HEAD + BODY * 400 + CONFIG.format(support=0).encode()
    s = server({"Корпус.gcode": big, "dir/other.gcode": gcode()})
    rel, settings, head = kp.read_settings(HOST, ROOT + "/Корпус.gcode")
    assert rel == "Корпус.gcode" and settings["layer_height"] == "0.2" and "Creality_Print V6.1.2" in head
    reads = [r for p, r in s.requests if p.startswith("/server/files/gcodes/")]
    assert reads == ["bytes=-2048", "bytes=0-%d" % (kp.HEAD_BYTES - 1)]   # never the whole file
    assert not kp.has_supports(settings)
    # the WS listing's other spelling of the folder: the one file of that name
    assert kp.read_settings(HOST, "/usr/data/printer_data/gcodes/other.gcode")[0] == "dir/other.gcode"
    assert kp.read_settings(HOST, "/usr/data/printer_data/gcodes/missing.gcode") is None


def test_settings_found_when_the_server_ignores_ranges(server, monkeypatch):
    monkeypatch.setattr(kp, "TAIL_BYTES", 2048)
    server({"a.gcode": HEAD + BODY * 400 + CONFIG.format(support=1).encode(), "plain.gcode": HEAD + BODY})
    rel, settings, _ = kp.read_settings(HOST, ROOT + "/a.gcode")
    assert settings["wall_loops"] == "3" and kp.has_supports(settings)
    assert kp.support_grams(HOST, rel) == pm.support_grams(io.BytesIO(HEAD + BODY * 400), time.monotonic() + 30)
    assert kp.read_settings(HOST, ROOT + "/plain.gcode") is None          # no config block (another slicer)


# --- the Creality client: the listing's card at once, the file's card next, one read per job ---

@pytest.fixture
def client(tmp_path, monkeypatch):
    from app.clients.creality_client import CrealityK1Client
    monkeypatch.setattr(job_previews, "DIRECTORY", tmp_path)
    monkeypatch.setattr(moonraker, "known", lambda host: True)
